/** @param {string} destination @param {{ name: string, tarball: string }[]} packages */
export function createReleaseBundle(destination, packages) {
  const directory = validateDestination(destination)
  const manifest = JSON.parse(readFileSync(join(repositoryRoot, 'package.json'), 'utf8'))
  const repositoryUrl = manifest.repository.url.replace(/^git\+/, '').replace(/\.git$/, '')
  if (!Array.isArray(packages) || packages.length !== packageNames.length
    || new Set(packages.map(entry => entry.name)).size !== packageNames.length) {
    throw new Error('release requires exactly one tarball for each of the four Nya packages')
  }
  const archives = packageNames.map(name => {
    const entry = packages.find(item => item.name === name)
    if (!entry) throw new Error(`missing release dependency: ${name}`)
    const packageManifest = JSON.parse(readFileSync(
      join(repositoryRoot, 'packages', name.slice('@nya/'.length), 'package.json'), 'utf8',
    ))
    if (packageManifest.name !== name || packageManifest.version !== manifest.version) {
      throw new Error(`release package name/version differs from the workspace: ${name}`)
    }
    const tarball = resolve(entry.tarball)
    const filename = `${name.replace('@', '').replace('/', '-')}-${packageManifest.version}.tgz`
    if (basename(tarball) !== filename || !lstatSync(tarball).isFile()) {
      throw new Error(`release tarball must match ${name}@${packageManifest.version}: ${tarball}`)
    }
    if (isDescendant(canonicalPath(directory), canonicalPath(tarball))) {
      throw new Error(`release input would be removed with its destination: ${tarball}`)
    }
    return {
      name, version: packageManifest.version, tarball,
      sha256: createHash('sha256').update(readFileSync(tarball)).digest('hex'),
      path: `vendor/${filename}`,
    }
  })
  // 缺少文档或示例构建产物时，在删除上一次候选之前失败。
  const copiedDocuments = [...documents].map(([source, target]) => ({
    target,
    content: rewriteMarkdown(readFileSync(join(repositoryRoot, source), 'utf8'), source, target, repositoryUrl),
  }))
  for (const entry of ['src', 'dist', 'scripts', 'tests', 'config.json', 'tsconfig.json', 'tsconfig.test.json', 'package.json']) {
    if (!existsSync(join(repositoryRoot, 'examples/task-journal', entry))) {
      throw new Error(`example bundle input is missing: ${entry}; build the workspace first`)
    }
  }
  if (existsSync(directory)) removeMarkedDirectory(directory, marker)
  mkdirSync(join(directory, 'vendor'), { recursive: true })
  writeFileSync(join(directory, marker), markerContent)
  for (const archive of archives) cpSync(archive.tarball, join(directory, archive.path))
  createExampleBundle(join(directory, 'task-journal'), archives)
  for (const document of copiedDocuments) writeFileSync(join(directory, document.target), document.content)
  writeFileSync(join(directory, 'RELEASE.json'), `${JSON.stringify({
    schemaVersion: 1,
    name: 'nya-release-candidate',
    version: manifest.version,
    node: manifest.engines.node,
    published: false,
    packages: archives.map(({ tarball: _tarball, ...entry }) => entry),
    documents: {
      changelog: 'CHANGELOG.md', compatibility: 'COMPATIBILITY.md',
      migration: 'MIGRATION.md', tutorial: 'TUTORIAL.md',
    },
    example: 'task-journal',
  }, null, 2)}\n`)
  writeFileSync(join(directory, 'SHA256SUMS'), archives.map(entry => `${entry.sha256}  ${entry.path}\n`).join(''))
  writeFileSync(join(directory, 'README.md'), releaseReadme(manifest, archives, repositoryUrl))
  return directory
}

function pack() {
  const npmCli = process.env.npm_execpath
  if (!npmCli) throw new Error('run this command through npm run release:pack')
  const staging = mkdtempSync(join(temporaryRoot, 'nya-release-pack-'))
  writeFileSync(join(staging, stagingMarker), markerContent)
  try {
    const env = { ...process.env }
    delete env.npm_config_dry_run
    delete env.NPM_CONFIG_DRY_RUN
    const packages = packageNames.map(name => {
      const [result] = JSON.parse(execFileSync(process.execPath, [
        npmCli, 'pack', '--workspace', name, '--pack-destination', staging, '--json',
      ], { cwd: repositoryRoot, env, encoding: 'utf8' }))
      if (result.name !== name || basename(result.filename) !== result.filename) {
        throw new Error(`unexpected npm pack result for ${name}`)
      }
      return { name, tarball: join(staging, result.filename) }
    })
    const directory = createReleaseBundle(join(artifactRoot, 'release-candidate'), packages)
    console.log(`本地发布候选已生成：${directory}`)
    console.log('版本与校验值见 RELEASE.json；安装、教程和示例见 README.md。未执行发布。')
  } finally {
    removeMarkedDirectory(staging, stagingMarker)
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) pack()

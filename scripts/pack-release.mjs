/** 生成可搬移的本地发布候选目录；不安装依赖，也不发布 npm 包。 */

import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import {
  cpSync, existsSync, lstatSync, mkdirSync, mkdtempSync, readFileSync,
  realpathSync, rmSync, writeFileSync,
} from 'node:fs'
import { tmpdir } from 'node:os'
import { basename, dirname, isAbsolute, join, relative, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createExampleBundle } from './pack-example.mjs'

const repositoryRoot = resolve(import.meta.dirname, '..')
const artifactRoot = join(repositoryRoot, 'artifacts')
const temporaryRoot = resolve(tmpdir())
const marker = '.nya-release-bundle'
const stagingMarker = '.nya-release-staging'
const markerContent = 'Generated by scripts/pack-release.mjs.\n'
const packageNames = ['@nya/core', '@nya/loader', '@nya/logger-console', '@nya/timer']
const documents = new Map([
  ['CHANGELOG.md', 'CHANGELOG.md'],
  ['docs/compatibility.md', 'COMPATIBILITY.md'],
  ['docs/how-to/migrate-0.1.md', 'MIGRATION.md'],
  ['docs/tutorials/framework-basics.md', 'TUTORIAL.md'],
  ['examples/task-journal/README.md', 'task-journal/README.md'],
])

function isDescendant(root, target) {
  const path = relative(root, target)
  return path !== '' && path !== '..' && !path.startsWith(`..${sep}`) && !isAbsolute(path)
}

// 未创建的目标也按最近存在祖先的真实路径校验，阻止父目录中的 junction/symlink 越界。
function canonicalPath(path) {
  if (existsSync(path)) return realpathSync(path)
  const parent = dirname(path)
  if (parent === path) throw new Error(`cannot resolve destination: ${path}`)
  return join(canonicalPath(parent), basename(path))
}

function validateDestination(destination) {
  if (typeof destination !== 'string' || !isAbsolute(destination)) {
    throw new Error('release destination must be an absolute path')
  }
  const directory = resolve(destination)
  const allowed = [artifactRoot, temporaryRoot].some(root => (
    isDescendant(root, directory)
    && isDescendant(canonicalPath(root), canonicalPath(directory))
  ))
  if (!allowed) throw new Error(`release destination must be below artifacts or the system temp directory: ${directory}`)
  if (existsSync(directory)) {
    const stat = lstatSync(directory)
    if (!stat.isDirectory() || stat.isSymbolicLink()) {
      throw new Error(`release destination must be a regular directory: ${directory}`)
    }
  }
  return directory
}

function removeMarkedDirectory(destination, markerName) {
  const directory = validateDestination(destination)
  const markerPath = join(directory, markerName)
  if (!existsSync(markerPath)
    || !lstatSync(markerPath).isFile()
    || lstatSync(markerPath).isSymbolicLink()
    || readFileSync(markerPath, 'utf8') !== markerContent) {
    throw new Error(`refusing to replace an unmarked directory: ${directory}`)
  }
  rmSync(directory, { recursive: true, force: true })
}

function rewriteMarkdown(markdown, source, destination, repositoryUrl) {
  function rewriteTarget(raw) {
    const angled = raw.startsWith('<') && raw.endsWith('>')
    const target = angled ? raw.slice(1, -1) : raw
    if (/^(?:[a-z][a-z\d+.-]*:|\/\/|#)/i.test(target)) return raw
    const suffixIndex = target.search(/[?#]/)
    const path = suffixIndex < 0 ? target : target.slice(0, suffixIndex)
    const suffix = suffixIndex < 0 ? '' : target.slice(suffixIndex)
    if (!path) return raw
    const decoded = decodeURIComponent(path)
    const sourceTarget = resolve(
      decoded.startsWith('/') ? repositoryRoot : dirname(join(repositoryRoot, source)),
      decoded.startsWith('/') ? `.${decoded}` : decoded,
    )
    if (!isDescendant(repositoryRoot, sourceTarget) && sourceTarget !== repositoryRoot) {
      throw new Error(`documentation link leaves the repository: ${source}: ${target}`)
    }
    const sourceRelative = relative(repositoryRoot, sourceTarget).split(sep).join('/')
    const mapped = documents.get(sourceRelative)
    // task-journal 自身随包提供的源码、配置和测试仍然可离线打开。
    const exampleLocal = source === 'examples/task-journal/README.md'
      && sourceRelative.startsWith('examples/task-journal/')
      ? sourceRelative.replace(/^examples\/task-journal\//, 'task-journal/')
      : undefined
    const output = mapped ?? exampleLocal
    const rewritten = output
      ? relative(dirname(join('/', destination)), join('/', output)).split(sep).join('/')
      : `${repositoryUrl}/blob/main/${sourceRelative.split('/').map(encodeURIComponent).join('/')}`
    return angled ? `<${rewritten}${suffix}>` : `${rewritten}${suffix}`
  }

  // 保留教程代码块原文，只处理 Markdown 正文中的内联链接和引用定义。
  let fence
  return markdown.split(/(?<=\n)/).map(line => {
    const delimiter = /^ {0,3}(`{3,}|~{3,})/.exec(line)?.[1]
    if (fence) {
      if (delimiter?.[0] === fence[0] && delimiter.length >= fence.length) fence = undefined
      return line
    }
    if (delimiter) {
      fence = delimiter
      return line
    }
    return line
      .replace(/(!?\[[^\]\n]*\]\()(<[^>\n]+>|[^\s)]+)([^\n)]*\))/g,
        (_match, prefix, target, suffix) => `${prefix}${rewriteTarget(target)}${suffix}`)
      .replace(/^( {0,3}\[[^\]\n]+\]:\s*)(<[^>\n]+>|\S+)(.*)$/,
        (_match, prefix, target, suffix) => `${prefix}${rewriteTarget(target)}${suffix}`)
  }).join('')
}

